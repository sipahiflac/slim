function wrapBitmapText(text,maxWidth,maxLines,font=FONTS.Regular) {
    const words=String(text).replace(/\s+/g,' ').trim().split(' ').filter(Boolean),lines=[];
    for(const word of words) {
        let rest=word;
        if(lines.length && measureString(lines[lines.length-1]+' '+rest,font)<=maxWidth) {
            lines[lines.length-1]+=' '+rest;continue;
        }
        while(rest.length) {
            const room=fitText(rest,maxWidth,font) || rest[0];
            lines.push(room);rest=rest.slice(room.length);
            if(lines.length>=maxLines)return lines;
        }
    }
    return lines.slice(0,maxLines);
}
