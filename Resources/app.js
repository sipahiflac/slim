// 1. Anti-web Restrictions
window.addEventListener('contextmenu', e => e.preventDefault());
window.addEventListener('selectstart', e => {if(e.target?.id!=='ai-prompt-input')e.preventDefault();});
window.addEventListener('dragstart', e => {
    e.preventDefault();
});
window.addEventListener('wheel', e => {
    if(e.ctrlKey)e.preventDefault();
    else if(e.deltaY||e.deltaX)wakeBacklight();
}, { passive: false });
window.addEventListener('keydown', e => {
    // Release build: the developer chords (Ctrl+Shift+E/D/F/M/B, demo macros, F12 screenshots) are not wired.
    if ((e.ctrlKey || e.metaKey) && ['+', '-', '=', '0', 'r', 'R'].includes(e.key)) e.preventDefault();
    if (e.key === 'F12') { e.preventDefault(); e.stopImmediatePropagation(); return; } // no WebView dev tools
    if (e.key === 'F5') e.preventDefault();
    if(!e.ctrlKey&&!e.altKey&&!e.metaKey&&!e.phonePhysical&&!navigationFeedbackSuppressed){
        const selector=e.phoneFeedbackSelector||{
            ArrowUp:'.nav-up',ArrowDown:'.nav-down',ArrowLeft:'.nav-left',ArrowRight:'.nav-right',
            Enter:'.soft-left',' ':'.nav-center',Escape:'.soft-right',Backspace:'.soft-right'
        }[e.key];
        const textEditing=['ai-prompt-input','license-code-input'].includes(e.target?.id);
        if(selector&&!(textEditing&&(e.key===' '||e.key==='Backspace'&&e.target.value.length)))pulsePhysicalKey(selector);
    }
}, true);

