function drawNeuralNetwork(elapsed){
    if(!Number.isFinite(elapsed))return;
    // Compact, centered 2–3–3–1 network with filled pixel-round neurons.
    const layers=[{x:10,ys:[24,36]},{x:34,ys:[20,30,40]},
                  {x:58,ys:[20,30,40]},{x:82,ys:[30]}];
    const clamp01=value=>Math.max(0,Math.min(1,value));
    const bezierEase=progress=>{
        const p=clamp01(progress),x1=0.42,y1=0.0,x2=0.58,y2=1.0;
        if(p<=0)return 0;
        if(p>=1)return 1;
        let low=0,high=1,t=p;
        for(let i=0;i<12;i++){
            t=(low+high)*0.5;
            const inverse=1-t;
            const x=3*inverse*inverse*t*x1+3*inverse*t*t*x2+t*t*t;
            if(x<p)low=t;else high=t;
        }
        const inverse=1-t;
        return 3*inverse*inverse*t*y1+3*inverse*t*t*y2+t*t*t;
    };
    const drawLine=(x0,y0,x1,y1)=>{
        let dx=Math.abs(x1-x0),sx=x0<x1?1:-1,dy=-Math.abs(y1-y0),sy=y0<y1?1:-1,error=dx+dy;
        const points=[];
        for(;;){points.push([x0,y0]);ctx.fillRect(x0,y0,1,1);if(x0===x1&&y0===y1)break;const twice=2*error;if(twice>=dy){error+=dy;x0+=sx;}if(twice<=dx){error+=dx;y0+=sy;}}
        return points;
    };
    const circle=['..###..','.#####.','#######','#######','#######','.#####.','..###..'];
    const toneMix=amount=>{
        const base=getColor(2).match(/[0-9a-f]{2}/gi),light=getColor(1).match(/[0-9a-f]{2}/gi);
        return `rgb(${base.map((value,index)=>Math.round(parseInt(value,16)+(parseInt(light[index],16)-parseInt(value,16))*amount)).join(',')})`;
    };
    const isValidNode=(layer,node)=>Number.isInteger(layer)&&Number.isInteger(node)
        &&layer>=0&&layer<layers.length&&node>=0&&node<layers[layer].ys.length;
    const drawNode=(layer,node,color=getColor(2))=>{
        if(!isValidNode(layer,node))return;
        ctx.fillStyle=color;
        const x=layers[layer].x,y=layers[layer].ys[node];
        for(let row=0;row<7;row++)for(let col=0;col<7;col++)if(circle[row][col]==='#')ctx.fillRect(x+col,y+row,1,1);
    };
    const drawNodeGlow=(layer,node,intensity)=>{
        if(!isValidNode(layer,node)||!Number.isFinite(intensity)||intensity<=0)return;
        // Pulse the node's ink only; keep its pixel footprint fixed in place.
        drawNode(layer,node,toneMix(0.92*intensity));
    };
    const drawEdge=(layer,source,target,color,amount=1)=>{
        if(!Number.isInteger(layer)||layer<0||layer>=layers.length-1
            ||!isValidNode(layer,source)||!isValidNode(layer+1,target)||!Number.isFinite(amount))return;
        const from=layers[layer],to=layers[layer+1];
        const x1=from.x+7,y1=from.ys[source]+3,x2=to.x-1,y2=to.ys[target]+3;
        ctx.fillStyle=color;
        return drawLine(x1,y1,Math.round(x1+(x2-x1)*amount),Math.round(y1+(y2-y1)*amount));
    };
    // Nodes arrive with a short, one-at-a-time “tak tak” cadence.
    const nodeStep=0.0567,nodeCount=9;
    const shownNodes=Math.min(nodeCount,Math.floor(elapsed/nodeStep)+1);
    let flatIndex=0,latestNode=null;
    for(let layer=0;layer<layers.length;layer++)for(let node=0;node<layers[layer].ys.length;node++){
        if(flatIndex<shownNodes){drawNode(layer,node,getColor(2));if(flatIndex===shownNodes-1)latestNode=[layer,node];}
        flatIndex++;
    }
    // Then the connections are drawn in three left-to-right passes.
    const linksStart=nodeCount*nodeStep+0.04;
    for(let layer=0;layer<3;layer++){
        const from=layers[layer],to=layers[layer+1];
        const reveal=bezierEase(clamp01((elapsed-(linksStart+layer*0.1267))/0.2267));
        if(reveal<=0)continue;
        for(let source=0;source<from.ys.length;source++)for(let target=0;target<to.ys.length;target++){
            drawEdge(layer,source,target,getColor(2),reveal);
        }
    }
    if(latestNode&&elapsed<nodeCount*nodeStep)drawNodeGlow(latestNode[0],latestNode[1],1);

    // The first route starts after the network is assembled; later routes
    // move twice as fast as the old preview and continue while synthesis runs.
    const routes=[[0,1,2,0],[1,2,1,0],[0,2,0,0],[1,0,2,0]];
    const signalStart=linksStart+2*0.1267+0.2267+0.03;
    if(elapsed<signalStart)return;
    const routePeriod=1.85;
    const routeNumber=elapsed<3?0:1+Math.floor((elapsed-3)/routePeriod);
    const route=routes[routeNumber%routes.length];
    const tripTime=elapsed<3?Math.max(0,elapsed-signalStart):(elapsed-3)%routePeriod;
    const routeStart=elapsed<3?signalStart:3+Math.floor((elapsed-3)/routePeriod)*routePeriod;
    const glowDuration=0.34;
    for(let index=0;index<route.length;index++){
        const age=elapsed-(routeStart+index*0.48);
        if(age>=0&&age<glowDuration){
            const fade=1-age/glowDuration;
            drawNodeGlow(index,route[index],fade);
        }
    }
    // Let the arrival bloom fade out cleanly before beginning the next route.
    if(tripTime>=1.44)return;
    const stage=Math.min(2,Math.floor(Math.max(0,tripTime)/0.48));
    const progress=(Math.max(0,tripTime)-stage*0.48)/0.48;
    const activeSource=route[stage],activeTarget=route[stage+1];
    const from=layers[stage],to=layers[stage+1];
    const x1=from.x+3,y1=from.ys[activeSource]+3,x2=to.x+3,y2=to.ys[activeTarget]+3;
    // Nearby branches catch a faint reflected glow from the active path.
    const reflected=toneMix(0.58);
    for(let target=0;target<layers[stage+1].ys.length;target++)if(target!==activeTarget)drawEdge(stage,activeSource,target,reflected);
    if(stage>0)for(let source=0;source<layers[stage-1].ys.length;source++)if(source!==route[stage-1])drawEdge(stage-1,source,activeSource,reflected);
    if(stage<2)for(let target=0;target<layers[stage+2].ys.length;target++)if(target!==activeTarget)drawEdge(stage+1,activeTarget,target,reflected);
    const activePath=drawEdge(stage,activeSource,activeTarget,toneMix(0.90));

    const pointIndex=Math.round(bezierEase(progress)*Math.max(0,activePath.length-1));
    const [pointX,pointY]=activePath[pointIndex]||[x1,y1];
    ctx.fillStyle=getColor(1);
    ctx.fillRect(pointX,pointY,2,2);
}
function drawLcdWaveform(minValues,maxValues,options={}) {
    const x0=options.x??7,width=options.width??82,mid=options.mid??40,amplitude=options.amplitude??11;
    const columns=Math.max(2,Math.floor(width/2));
    const top=[],bottom=[];
    for(let column=0;column<columns;column++) {
        const from=Math.floor(column*minValues.length/columns);
        const to=Math.max(from+1,Math.floor((column+1)*minValues.length/columns));
        let low=0,high=0;
        for(let i=from;i<Math.min(to,minValues.length,maxValues.length);i++) {
            low=Math.min(low,Number(minValues[i])||0);
            high=Math.max(high,Number(maxValues[i])||0);
        }
        top.push(mid-Math.round(Math.max(0,Math.min(1,high))*amplitude));
        bottom.push(mid-Math.round(Math.min(0,Math.max(-1,low))*amplitude));
    }

    // The old Nokia displays suggested a waveform with a handful of hard
    // pixels. Keep the centre guide sparse, then draw a stepped 1-bit contour
    // rather than filling every column like a modern editor thumbnail.
    ctx.fillStyle=getColor(2);
    for(let x=x0;x<x0+width;x+=4)ctx.fillRect(x,mid,2,1);
    ctx.fillStyle=getColor(1);
    for(let i=0;i<columns;i++) {
        const x=x0+i*2;
        ctx.fillRect(x,top[i],2,1);
        ctx.fillRect(x,bottom[i],2,1);
        if(i>0) {
            const previousTop=top[i-1],previousBottom=bottom[i-1];
            ctx.fillRect(x,Math.min(previousTop,top[i]),1,Math.abs(top[i]-previousTop)+1);
            ctx.fillRect(x,Math.min(previousBottom,bottom[i]),1,Math.abs(bottom[i]-previousBottom)+1);
        }
        if(i%4===0 && bottom[i]-top[i]>4) {
            ctx.fillStyle=getColor(2);
            ctx.fillRect(x,top[i]+2,1,bottom[i]-top[i]-3);
            ctx.fillStyle=getColor(1);
        }
    }
}

