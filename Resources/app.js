async function finishStartup(){
    const boot=window.phoneBoot;if(!boot)return;
    try{
        boot.mark('DISPLAY');
        boot.info(['LCD 96X73 PIXELS',`BITMAP FONT ${Object.keys(REGULAR_GLYPHS).length} GLYPHS`,'LCD RENDERER INITIALIZED']);
        await boot.assets;
        if(document.readyState!=='complete')await new Promise(resolve=>window.addEventListener('load',resolve,{once:true}));
        boot.mark('ARTWORK');
        boot.info([`DEVICE PNG ${phoneArtSource.naturalWidth}X${phoneArtSource.naturalHeight}`,`KEYCAPS ${keyFaces.size}`,'DESK SVG DECODED']);
        const backend=window.__JUCE__?.backend;
        const statusFn=backend?.getNativeFunction?.('getStartupStatus');
        let status={library:!backend,audio:!backend};
        if(backend&&!statusFn)throw new Error('Startup handshake unavailable');
        while(!status.library){
            status=unwrapNativeResult(await statusFn());
            if(!status.library)await new Promise(resolve=>setTimeout(resolve,40));
        }
        if(backend){const raw=await backend.getNativeFunction('getInstruments')();if(!applyInstrumentLibrary(raw))throw new Error('Library unavailable');}
        boot.mark('LIBRARY');
        boot.info([`SAMPLES ${instrumentList.length}`,`GENERATED ${instrumentCategories.filter(category=>category==='Generated').length}`,`UPLOADED ${instrumentCategories.filter(category=>category==='Uploaded').length}`]);
        await Promise.all(keySoundLoads);
        if(keySounds.size!==2)throw new Error('Key sounds unavailable');
        while(!status.audio){status=unwrapNativeResult(await statusFn());if(!status.audio)await new Promise(resolve=>setTimeout(resolve,40));}
        boot.mark('AUDIO');
        boot.info([`KEY SOUNDS ${keySounds.size}`,`ENGINE ${status.engineRate||16000} HZ`,
            status.outputRate>0?`OUTPUT ${status.outputRate} HZ`:'OUTPUT HOST IDLE',
            status.blockSize>0?`BLOCK ${status.blockSize} SAMPLES`:'BLOCK HOST MANAGED',
            `CHANNELS ${status.channels??0}`]);
        render();await boot.finish();
    }catch(error){console.warn('Startup:',error);boot.fail();}
}
