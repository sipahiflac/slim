function playKeySound(name) {
    if(phoneSettings.keyVolume===0)return;
    if (keyAudio.state === 'suspended') keyAudio.resume().catch(() => {});
    const buffer = keySounds.get(name);
    if (!buffer) return;
    const source = keyAudio.createBufferSource();
    const gain = keyAudio.createGain();
    source.buffer = buffer;
    gain.gain.value = 0.45*Math.pow(phoneSettings.keyVolume/7,2)*(window.getMasterVolumeGain?.()??1);
    source.connect(gain).connect(keyAudio.destination);
    source.onended = () => { source.disconnect(); gain.disconnect(); };
    source.start();
}

