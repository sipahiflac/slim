function measureString(str, font) {
 return Array.from(str).reduce((w, c, i) => w + font.getGlyph(c).w + (i ? font.spacing : 0), 0);
}
function drawString(startX, startY, str, font, toneIdx) {
 let x = Math.round(startX);
 ctx.fillStyle = getColor(toneIdx);
 for (const c of str) {
  const glyph = font.getGlyph(c);
  const top = Math.round(startY) + (glyph.dy || 0);
  glyph.rows.forEach((row, y) => {
   for (let col = 0; col < glyph.w; col++)
    if (row & (1 << (glyph.w-col-1))) ctx.fillRect(x+col, top+y, 1, 1);
  });
  x += glyph.w + font.spacing;
 }
}

function drawStringInkCentered(y, str, font, toneIdx) {
    let pen = 0, min = Infinity, max = -Infinity;
    for (const c of str) {
        const glyph = font.getGlyph(c);
        glyph.rows.forEach(row => {
            for (let col = 0; col < glyph.w; col++)
                if (row & (1 << (glyph.w - col - 1))) { min = Math.min(min, pen + col); max = Math.max(max, pen + col); }
        });
        pen += glyph.w + font.spacing;
    }
    if (!isFinite(min)) return;
    drawString(Math.floor((96 - (max - min + 1)) / 2) - min, y, str, font, toneIdx);
}
function drawStringCentered(y, str, font, toneIdx) {
    const w = measureString(str, font);
    const x = Math.floor((96 - w) / 2);
    drawString(x, y, str, font, toneIdx);
}

