function animateRockerLight(face,direction){
    cancelAnimationFrame(face.lightFrame);
    const from=face.lightVector||[0,0,0];
    const to=direction==='up'?[0,.035,-.025]:direction==='down'?[0,-.035,-.025]:
        direction==='left'?[.035,0,-.025]:direction==='right'?[-.035,0,-.025]:direction?[0,0,-.035]:[0,0,0];
    const started=performance.now(),duration=direction?75:110;
    const original=face.restPixels,context=face.getContext('2d');
    const frame=context.createImageData(face.width,face.height);
    function tick(now){
        const t=Math.min(1,(now-started)/duration),ease=t*t*(3-2*t);
        const light=from.map((value,i)=>value+(to[i]-value)*ease);face.lightVector=light;
        frame.data.set(original.data);
        for(let y=0;y<face.height;y++)for(let x=0;x<face.width;x++){
            const index=(y*face.width+x)*4;if(!frame.data[index+3])continue;
            const shade=1+light[2]+light[0]*(2*x/Math.max(1,face.width-1)-1)+light[1]*(2*y/Math.max(1,face.height-1)-1);
            for(let c=0;c<3;c++)frame.data[index+c]=Math.min(255,Math.round(original.data[index+c]*shade));
        }
        context.putImageData(frame,0,0);
        if(t<1)face.lightFrame=requestAnimationFrame(tick);
    }
    face.lightFrame=requestAnimationFrame(tick);
}
