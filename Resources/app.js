function updateEditParameter(parameterIndex, value) {
    const backendParameter=EDIT_PARAMETERS[parameterIndex].parameter;
    editValues[backendParameter] = Math.max(1, Math.min(editMaximum(parameterIndex), Number(value)));
    const matchingSlider = editSliders.querySelector(`input[data-parameter="${parameterIndex}"]`);
    if (matchingSlider) matchingSlider.value = String(editValues[backendParameter]);
    if(matchingSlider&&backendParameter===0)matchingSlider.setAttribute('aria-valuetext',brightnessLabel(editValues[0]));
    emitJuce('setVoiceParam', { instrument: selectedVoiceIndex, parameter: backendParameter, value: editValues[backendParameter] });
    render();
}

function stepEditParameter(parameterIndex, direction, fine=false) {
    const value = editValues[EDIT_PARAMETERS[parameterIndex].parameter];
    const stepped = fine?value+direction*.1:direction > 0
        ? Math.floor(value + 0.0001) + 1
        : Math.ceil(value - 0.0001) - 1;
    updateEditParameter(parameterIndex, stepped);
}

function loadEditValues() {
    const index=selectedVoiceIndex;
    const backend = window.__JUCE__ && window.__JUCE__.backend;
    if (!backend || typeof backend.getNativeFunction !== 'function') return;
    const fn = backend.getNativeFunction('getVoiceParams');
    if (!fn) return;
    fn(index).then(value => {
        if(index!==selectedVoiceIndex)return;
        let values = value;
        while (Array.isArray(values) && values.length === 1 && Array.isArray(values[0])) values = values[0];
        if (Array.isArray(values) && values.length >= 7) {
            editValues = values.slice(0, 7).map(v => Math.max(1, Math.min(10, Number(v) || 1)));
            editSliders.dataset.signature = '';
            render();
        }
    }).catch(() => {});
    const editorFn=backend.getNativeFunction('getInstrumentEditorData');
    if(editorFn)editorFn(index).then(raw=>{
        if(index!==selectedVoiceIndex)return;
        const data=unwrapNativeResult(raw);if(!data.ok)return;
        editWaveformMin=Array.isArray(data.waveformMin)?data.waveformMin.map(Number):Array(82).fill(0);
        editWaveformMax=Array.isArray(data.waveformMax)?data.waveformMax.map(Number):Array(82).fill(0);
        editSampleStart=Math.max(0,Math.min(.98,Number(data.start)||0));
        editSampleEnd=Math.max(editSampleStart+.02,Math.min(1,Number(data.end)||1));
        editRootNote=Math.max(0,Math.min(127,Math.round(Number.isFinite(Number(data.rootNote))?Number(data.rootNote):60)));
        editRootCents=Number(data.rootCents)||0;editPitched=!!data.pitched;editUseOriginal=!!data.useOriginal;
        editLoopRegions=Array.isArray(data.loops)?data.loops.map(loop=>({
            start:Math.max(0,Math.min(1,Number(loop.start)||0)),
            end:Math.max(0,Math.min(1,Number(loop.end)||0)),
            full:loop.full===true
        })).filter(loop=>loop.end>loop.start):[];
        editLoopSelection=Math.max(0,Math.min(editLoopRegions.length,Math.round(Number(data.loop)||0)));
        render();
    }).catch(()=>{});
}

