// recording (vibration.wav). It is fetched in the background; boot does not wait for it.
let vibrationBuffer=null;
function playInboxVibration(){
    if(phoneSettings.keyVolume===0||!vibrationBuffer)return;
    if(keyAudio.state==='suspended')keyAudio.resume().catch(()=>{});
    const source=keyAudio.createBufferSource(),gain=keyAudio.createGain();
    source.buffer=vibrationBuffer;
    // The recording is a continuous buzz at about -5 dBFS RMS; this keeps it a notification, not an alarm.
    gain.gain.value=.25*Math.pow(phoneSettings.keyVolume/7,2)*Math.min(1,window.getMasterVolumeGain?.()??1);
    source.connect(gain).connect(keyAudio.destination);
    source.onended=()=>{source.disconnect();gain.disconnect();};
    source.start();
}
