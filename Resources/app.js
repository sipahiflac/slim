function drawPhoneArtwork() {
    const artCtx = phoneArtCanvas.getContext('2d');
    artCtx.clearRect(0, 0, phoneArtCanvas.width, phoneArtCanvas.height);
    artCtx.drawImage(phoneArtSource, 0, 0, phoneArtCanvas.width, phoneArtCanvas.height);
    if(keySocketFills.length){
        const w=phoneArtCanvas.width,h=phoneArtCanvas.height;
        const frame=artCtx.getImageData(0,0,w,h),outside=new Uint8Array(w*h),queue=[];
        const visit=index=>{
            if(!outside[index]&&frame.data[index*4+3]<16){outside[index]=1;queue.push(index);}
        };
        for(let x=0;x<w;x++){visit(x);visit((h-1)*w+x);}
        for(let y=0;y<h;y++){visit(y*w);visit(y*w+w-1);}
        for(let i=0;i<queue.length;i++){
            const index=queue[i],x=index%w,y=Math.floor(index/w);
            if(x>0)visit(index-1);if(x<w-1)visit(index+1);
            if(y>0)visit(index-w);if(y<h-1)visit(index+w);
        }
        // Seal the complete authored key holes, including the sliver beyond
        // the moving cap's silhouette. The workbench cannot show through them.
        for(let index=0;index<w*h;index++){
            if(outside[index]||frame.data[index*4+3]>=16)continue;
            const x=index%w,y=Math.floor(index/w);
            const fill=keySocketFills.reduce((best,key)=>
                !best||(key.x-x)**2+(key.y-y)**2<(best.x-x)**2+(best.y-y)**2?key:best,null);
            frame.data.set([...fill.rgb,255],index*4);
        }
        artCtx.putImageData(frame,0,0);
    }

    // Cover the new artwork screen bed at source resolution.
    artCtx.fillStyle = '#858b70';
    artCtx.fillRect(29, 94, 92, 70);

}

