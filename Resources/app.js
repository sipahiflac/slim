// 0..1: identical names score 1, a name that starts the other 0.95, otherwise the better of a character-trigram
// (typo tolerant) and a shared-word measure.
function demoSimilarity(a,b){
    if(!a||!b)return 0;
    if(a===b)return 1;
    if(a.startsWith(b)||b.startsWith(a))return .95;
    const ga=demoTrigrams(a),gb=demoTrigrams(b);let shared=0,total=0;
    ga.forEach((count,gram)=>{total+=count;shared+=Math.min(count,gb.get(gram)||0);});
    gb.forEach(count=>{total+=count;});
    const dice=2*shared/Math.max(1,total);
    const wa=new Set(a.split(' ')),wb=new Set(b.split(' '));let common=0;
    wa.forEach(word=>{if(wb.has(word))common++;});
    return Math.max(dice,common/Math.max(wa.size,wb.size));
}
// Index of the user's own sound (Generated or Uploaded) whose name is closest to what was typed; -1 if none.
function findDemoSound(typed){
    const full=demoNormalize(typed),clipped=demoNormalize(String(typed).slice(0,28));
    let best=-1,bestScore=-1;
    instrumentList.forEach((name,index)=>{
        if(!instrumentGenerated[index])return;
        const label=demoNormalize(name);
        const score=Math.max(demoSimilarity(full,label),demoSimilarity(clipped,label));
        if(score>bestScore){bestScore=score;best=index;}
    });
    return best;
}
